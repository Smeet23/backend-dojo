// Generates src/content/registry.ts from the lecture folders in src/content.
// Folder "NN-slug" (or "21.1-slug") maps to the lecture whose slug is "slug".
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const contentDir = path.join(import.meta.dirname, "..", "src", "content");

const folders = readdirSync(contentDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort((a, b) => parseFloat(a) - parseFloat(b));

const entries = folders.map((folder, i) => ({
  folder,
  slug: folder.replace(/^[\d.]+-/, ""),
  ident: `L${i}`,
}));

const imports = entries
  .map((e) => `import ${e.ident}Lesson from "./${e.folder}/lesson.mdx";\nimport { quiz as ${e.ident}Quiz } from "./${e.folder}/quiz";`)
  .join("\n");

const map = entries.map((e) => `  ${JSON.stringify(e.slug)}: { Lesson: ${e.ident}Lesson, quiz: ${e.ident}Quiz },`).join("\n");

writeFileSync(
  path.join(contentDir, "registry.ts"),
  `// Generated by scripts/gen-registry.mjs — run \`pnpm content:registry\` after adding a lecture folder.
import type { ComponentType } from "react";
import type { Question } from "@/lib/types";
${imports}

/** Lesson bodies and quizzes for each available lecture, keyed by slug. */
export const lessons: Record<string, { Lesson: ComponentType; quiz: Question[] }> = {
${map}
};

export const allQuestions: Question[] = Object.values(lessons).flatMap((l) => l.quiz);
`,
);

console.log(`registry.ts: ${entries.length} lectures (${entries.map((e) => e.slug).join(", ")})`);
