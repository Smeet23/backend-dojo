// Generates a registry.ts per course and src/content/courses/index.ts.
// Course folder: src/content/courses/<course>/ with lectures.ts (exports `course`, `lectures`)
// and one folder per lecture, "NN-slug" (or "21.1-slug"), holding lesson.mdx + quiz.ts.
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

const coursesDir = path.join(import.meta.dirname, "..", "src", "content", "courses");
const header = "// Generated by scripts/gen-registry.mjs — run `pnpm content:registry` after adding a course or lecture folder.\n";

const courseIds = readdirSync(coursesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(path.join(coursesDir, d.name, "lectures.ts")))
  .map((d) => d.name)
  .sort();

for (const courseId of courseIds) {
  const dir = path.join(coursesDir, courseId);
  const folders = readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort((a, b) => parseFloat(a) - parseFloat(b));
  const entries = folders.map((folder, i) => ({ folder, slug: folder.replace(/^[\d.]+-/, ""), ident: `L${i}` }));

  writeFileSync(
    path.join(dir, "registry.ts"),
    `${header}import type { ComponentType } from "react";
import type { Question } from "@/lib/types";
${entries.map((e) => `import ${e.ident}Lesson from "./${e.folder}/lesson.mdx";\nimport { quiz as ${e.ident}Quiz } from "./${e.folder}/quiz";`).join("\n")}

/** Lesson bodies and quizzes for each available lecture, keyed by slug. */
export const lessons: Record<string, { Lesson: ComponentType; quiz: Question[] }> = {
${entries.map((e) => `  ${JSON.stringify(e.slug)}: { Lesson: ${e.ident}Lesson, quiz: ${e.ident}Quiz },`).join("\n")}
};
`,
  );
  console.log(`${courseId}: ${entries.length} lectures`);
}

const ident = (id) => id.replace(/[^a-zA-Z0-9]/g, "_");
writeFileSync(
  path.join(coursesDir, "index.ts"),
  `${header}import type { ComponentType } from "react";
import type { Course, Lecture, Question } from "@/lib/types";
${courseIds
  .map(
    (id) =>
      `import { course as ${ident(id)}Course, lectures as ${ident(id)}Lectures } from "./${id}/lectures";\nimport { lessons as ${ident(id)}Lessons } from "./${id}/registry";`,
  )
  .join("\n")}

export type CourseContent = {
  course: Course;
  lectures: Lecture[];
  lessons: Record<string, { Lesson: ComponentType; quiz: Question[] }>;
};

/** Every course, in display order. */
export const courses: CourseContent[] = [
${courseIds.map((id) => `  { course: ${ident(id)}Course, lectures: ${ident(id)}Lectures, lessons: ${ident(id)}Lessons },`).join("\n")}
];
`,
);
console.log(`index.ts: ${courseIds.length} course(s)`);
