"use client";

import { useState } from "react";
import { Pill, Widget } from "./Widget";

type Body = Record<string, unknown>;
type Preset = { label: string; body: Body };

const COLUMNS = ["todo", "doing", "done"];
const KNOWN_TASKS = new Set([7, 8, 9]);

function presets(field: string): Preset[] {
  return [
    { label: "Valid", body: { taskId: 7, [field]: "done", actor: "maya" } },
    { label: "No actor", body: { taskId: 7, [field]: "doing" } },
    { label: "Old field name", body: { taskId: 7, [field === "to" ? "column" : "to"]: "done" } },
    { label: "Bad enum", body: { taskId: 7, [field]: "archived" } },
    { label: "Wrong type", body: { taskId: "7", [field]: "done" } },
    { label: "Unknown task", body: { taskId: 999, [field]: "done" } },
  ];
}

function specYaml(field: string): string {
  return `paths:
  /api/move:
    post:
      operationId: moveTask
      requestBody:
        required: true
        content:
          application/json:
            schema:
              type: object
              required: [taskId, ${field}]
              additionalProperties: false
              properties:
                taskId: { type: integer }
                ${field}: { type: string, enum: [todo, doing, done] }
                actor: { type: string, default: guest }
      responses:
        "200": { description: Moved, content: ... Event }
        "400": { description: Invalid request }
        "404": { description: Task not found }`;
}

function generatedTs(field: string): string {
  return `// generated by openapi-typescript
interface MoveTaskBody {
  taskId: number;
  ${field}: "todo" | "doing" | "done";
  actor?: string; // default "guest"
}`;
}

/** Validate against the schema exactly like a spec-driven validator would. */
function respond(field: string, body: Body): { status: string; lines: string[]; ok: boolean } {
  const errors: string[] = [];
  for (const key of Object.keys(body)) {
    if (!["taskId", field, "actor"].includes(key)) errors.push(`/${key}: unknown property (additionalProperties: false)`);
  }
  if (!("taskId" in body)) errors.push("/taskId: required");
  else if (typeof body.taskId !== "number" || !Number.isInteger(body.taskId)) errors.push(`/taskId: expected integer, got ${typeof body.taskId}`);
  if (!(field in body)) errors.push(`/${field}: required`);
  else if (!COLUMNS.includes(String(body[field]))) errors.push(`/${field}: must be one of todo, doing, done`);

  if (errors.length) return { status: "400 Bad Request", lines: [JSON.stringify({ errors }, null, 2)], ok: false };
  if (!KNOWN_TASKS.has(body.taskId as number)) {
    return { status: "404 Not Found", lines: [JSON.stringify({ error: "task 999 not found" }, null, 2)], ok: false };
  }
  const actor = typeof body.actor === "string" ? body.actor : "guest";
  return {
    status: "200 OK",
    lines: [JSON.stringify({ type: "task.moved", taskId: body.taskId, [field]: body[field], actor }, null, 2)],
    ok: true,
  };
}

export function OpenApiPlayground() {
  const [field, setField] = useState<"to" | "column">("to");
  const [pick, setPick] = useState(0);
  const [tab, setTab] = useState<"server" | "client">("server");

  const list = presets(field);
  const preset = list[pick];
  const res = respond(field, preset.body);
  const frontendCompiles = field === "to";

  return (
    <Widget
      title="OpenAPI playground"
      hint="One spec for the move endpoint. Send requests through a spec-driven validator, then rename a field and watch the generated client react."
    >
      <div className="flex flex-wrap items-center gap-2 text-sm">
        <span className="w-24 text-muted">Spec field</span>
        <Pill active={field === "to"} onClick={() => setField("to")}>to</Pill>
        <Pill active={field === "column"} onClick={() => setField("column")}>renamed to column</Pill>
      </div>

      <div className="mt-4 grid gap-4 sm:grid-cols-2">
        <div>
          <p className="mb-1 text-xs font-semibold uppercase tracking-wide text-muted">openapi.yaml (excerpt)</p>
          <pre className="overflow-x-auto rounded-lg bg-surface-2 p-3 font-mono text-[0.72rem] leading-5">{specYaml(field)}</pre>
        </div>

        <div>
          <div className="mb-2 flex flex-wrap gap-2">
            <Pill active={tab === "server"} onClick={() => setTab("server")}>Send a request</Pill>
            <Pill active={tab === "client"} onClick={() => setTab("client")}>Generated client</Pill>
          </div>

          {tab === "server" ? (
            <div className="space-y-2 text-sm">
              <div className="flex flex-wrap gap-2">
                {list.map((p, i) => (
                  <Pill key={p.label} active={pick === i} onClick={() => setPick(i)}>
                    {p.label}
                  </Pill>
                ))}
              </div>
              <pre className="whitespace-pre-wrap break-all rounded-lg border border-border p-3 font-mono text-[0.75rem] leading-5">
                {`POST /api/move\nContent-Type: application/json\n\n${JSON.stringify(preset.body)}`}
              </pre>
              <div className={`rounded-lg p-3 ${res.ok ? "bg-good-soft" : "bg-bad-soft"}`}>
                <p className="font-semibold">{res.status}</p>
                <pre className="mt-1 whitespace-pre-wrap break-all font-mono text-[0.75rem] leading-5">{res.lines.join("\n")}</pre>
              </div>
            </div>
          ) : (
            <div className="space-y-2 text-sm">
              <pre className="overflow-x-auto rounded-lg bg-surface-2 p-3 font-mono text-[0.72rem] leading-5">{generatedTs(field)}</pre>
              <p className="text-xs font-semibold uppercase tracking-wide text-muted">Existing frontend code</p>
              <pre className="overflow-x-auto rounded-lg border border-border p-3 font-mono text-[0.72rem] leading-5">
                {`await client.POST("/api/move", {\n  body: { taskId: 7, to: "done" },\n});`}
              </pre>
              <div className={`rounded-lg p-3 ${frontendCompiles ? "bg-good-soft" : "bg-bad-soft"}`}>
                {frontendCompiles ? (
                  <p>Type-checks. The call matches the contract.</p>
                ) : (
                  <p className="break-words">
                    <strong>Compile error:</strong> Object literal may only specify known properties, and &quot;to&quot; does not
                    exist in type MoveTaskBody. The drift is caught at build time, not by a user.
                  </p>
                )}
              </div>
            </div>
          )}
        </div>
      </div>
    </Widget>
  );
}
